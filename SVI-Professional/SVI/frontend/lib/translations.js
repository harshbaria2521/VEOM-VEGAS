/**
 * Fallback Proxy:
 * Ensures any translations[lang][key] never returns undefined, null, or [object Object].
 * If a key is missing in the target language, it gracefully falls back to English.
 */
export const translations = new Proxy(rawTranslations, {
  get(target, langKey) {
    if (typeof langKey !== 'string') return target[langKey];
    const dict = target[langKey] || target.en || {};
    return new Proxy(dict, {
      get(itemTarget, key) {
        if (typeof key !== 'string') return itemTarget[key];
        const val = itemTarget[key];
        if (val !== undefined && val !== null && val !== '') {
          return val;
        }
        if (target.en && target.en[key] !== undefined && target.en[key] !== null && target.en[key] !== '') {
          return target.en[key];
        }
        return '';
      }
    });
  }
});

/**
 * Returns true if the language code requires Right-to-Left (RTL) text direction.
 */
export function isRtlLang(code) {
  const langConfig = supportedLanguages.find((l) => l.code === code);
  return langConfig ? langConfig.dir === 'rtl' : ['ur', 'sd', 'ks'].includes(code);
}

/**
 * Returns the BCP-47 speech recognition language code if reliably supported, or null otherwise.
 */
export function getSpeechRecognitionLang(code) {
  const langConfig = supportedLanguages.find((l) => l.code === code);
  return langConfig ? langConfig.speechCode : (code === 'hi' ? 'hi-IN' : (code === 'en' ? 'en-IN' : null));
}
